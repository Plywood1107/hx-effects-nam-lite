#!/usr/bin/env python3
"""extract_fw_tables.py - the firmware's own model tables, for sending presets straight to the unit (fw-models.js).

A preset on the unit stores each block as a preset id, a block type and its knob values in the model's parameter
order (docs/hxedit-preset-format.md, "On the wire" and "Building presets"). Those come from the firmware image, not
from HX Edit: this reads them from Line 6's stock 3.80 file (the "stock" build) and from this repo's built images
(nam / amps / full, from build.py), with tools/preset_send.py model_table(), and writes fw-models.js:

  window.FW_MODELS = {builds: {stock: {symbol: [pid, block type, [[name, type, default, min, max], ...], display name], ...}, ...}}

type: 1 switch, 2 whole number, 3 decimal. In a built image a custom effect's host model carries the custom effect's
own knobs. fw-models.js holds Line 6 model data: it is git-ignored; run this on each machine after building.

usage: .venv/bin/python tools/preset-builder/extract_fw_tables.py
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import preset_send as ps  # noqa: E402

IMAGES = {
    'stock': os.path.join(REPO, 'firmware', 'HX_Effects_v3.80.0_0xd97239907.hxf'),
    'nam': os.path.join(REPO, 'build', 'HX_Effects_v3.80.0_NAM.hxf'),
    'amps': os.path.join(REPO, 'build', 'HX_Effects_v3.80.0_NAM_Amps.hxf'),
    'full': os.path.join(REPO, 'build', 'HX_Effects_v3.80.0_NAM_Amps_Effects.hxf'),
}


def num(x):
    if isinstance(x, (bool, int)):
        return x
    return None if math.isnan(x) else round(x, 6)


def main():
    out, missing = {}, []
    for build, image in IMAGES.items():
        if not os.path.isfile(image):
            missing.append(f'{build} ({os.path.relpath(image, REPO)})')
            continue
        by_name, _ = ps.model_table(image)
        out[build] = {name: [m['pid'], m['btype'], [[p['name'], p['type'], num(p['default']), num(p['min']), num(p['max'])]
                                                      for p in m['params']], m['display']]
                      for name, m in by_name.items()}
        print(f'{build}: {len(by_name)} models from {os.path.relpath(image, REPO)}')
    if missing:
        print('not found, so not offered for sending: ' + ', '.join(missing) + ' (build it with build.py)')
    path = os.path.join(HERE, 'fw-models.js')
    with open(path, 'w') as f:
        f.write('// Generated by extract_fw_tables.py from the firmware images: Line 6 data, do not commit.\n')
        f.write('window.FW_MODELS = ' + json.dumps({'builds': out}, separators=(',', ':')) + ';\n')
    print(f'wrote {os.path.relpath(path, REPO)} ({os.path.getsize(path) // 1024} KB)')


if __name__ == '__main__':
    main()
