#!/usr/bin/env node
// make_catalog.js - the preset builder's model catalogue (fw-catalog.js), extracted from Line 6's HX Effects firmware.
//
// The page needs each model's name, category, legacy flag, DSP cost, preset id and block type, and each knob's name,
// range, default and display details. Those are read here, once, from the stock 3.80 firmware and from this repo's
// three builds of it (the setup page's recipes, web/recipe-*.bin), with the page's own reader (fw-reader.js), and
// written as our own data file: no Line 6 file or code goes into the repo or onto the website, only the extracted
// tables. The page loads fw-catalog.js and no longer asks for the firmware file.
//
// Layout: window.FW_CATALOG = {version, stock: {name: model},
//   nam|amps|full: {changed: {name: model}, removed: [name], order?: [name]}},
// each build stored as its differences from the build before it (stock -> nam -> amps -> full); order, where given,
// is the firmware's model order for that build (the page's model ids depend on it).
//
// usage: node tools/preset-builder/make_catalog.js [path/to/HX_Effects_v3.80.0_0xd97239907.hxf]
//        (default: firmware/HX_Effects_v3.80.0_0xd97239907.hxf). Needs only Node.
"use strict";
const fs = require("fs"), path = require("path"), zlib = require("zlib"), crypto = require("crypto");
const HERE = __dirname, REPO = path.resolve(HERE, "..", "..");
const FWREAD = require(path.join(HERE, "fw-reader.js"));
const FIRMWARE = require(path.join(REPO, "web", "firmware-core.js"));

const ORDER = ["stock", "nam", "amps", "full"];
const env = {
  pako: { inflate: b => new Uint8Array(zlib.inflateSync(b)) },
  md5: b => crypto.createHash("md5").update(b).digest("hex"),
};

function main() {
  const file = process.argv[2] || path.join(REPO, "firmware", "HX_Effects_v3.80.0_0xd97239907.hxf");
  const stock = new Uint8Array(fs.readFileSync(file));
  const cat = { stock: FWREAD.read(FIRMWARE.stockArchive(stock, env.pako)) };
  for (const b of ORDER.slice(1)) {
    const recipe = new Uint8Array(fs.readFileSync(path.join(REPO, "web", `recipe-${b}.bin`)));
    cat[b] = FWREAD.read(FIRMWARE.archive(stock, recipe, env));       // throws unless it is the stock 3.80 file
  }
  if (!Object.values(cat.stock).some(m => m.legacy === true)) throw new Error("fw-reader.js gave no legacy flags");
  const out = { version: 1, stock: cat.stock };
  for (let i = 1; i < ORDER.length; i++) {
    const prev = cat[ORDER[i - 1]], cur = cat[ORDER[i]], changed = {};
    for (const [n, m] of Object.entries(cur)) if (JSON.stringify(prev[n]) !== JSON.stringify(m)) changed[n] = m;
    out[ORDER[i]] = { changed, removed: Object.keys(prev).filter(n => !(n in cur)) };
    // the firmware's own model order, where merging changes it: the page's model ids depend on it
    if (JSON.stringify(Object.keys(expandOne(cat[ORDER[i - 1]], out[ORDER[i]]))) !== JSON.stringify(Object.keys(cur)))
      out[ORDER[i]].order = Object.keys(cur);
  }
  const dest = path.join(HERE, "fw-catalog.js");
  fs.writeFileSync(dest, "// Generated by make_catalog.js from the HX Effects 3.80 firmware and this repo's builds of it: extracted model\n" +
    "// tables (names, knobs, ranges, costs), no Line 6 file or code. Regenerate it whenever a recipe changes.\n" +
    "window.FW_CATALOG = " + JSON.stringify(out) + ";\n");
  console.log(`wrote ${path.relative(REPO, dest)} (${Math.round(fs.statSync(dest).size / 1024)} KB): ` +
    ORDER.map(b => `${b} ${Object.keys(cat[b]).length}`).join(", ") + " models");
}

// one build from the build before it and its differences (the page has the same code: index.html expandCatalog)
function expandOne(prev, d) {
  const m = { ...prev, ...d.changed };
  for (const n of d.removed) delete m[n];
  return d.order ? Object.fromEntries(d.order.map(n => [n, m[n]])) : m;
}
// FW_CATALOG -> {build: {name: model}}, as the page uses it
function expand(c) {
  const cat = { stock: c.stock };
  for (let i = 1; i < ORDER.length; i++) cat[ORDER[i]] = expandOne(cat[ORDER[i - 1]], c[ORDER[i]]);
  return cat;
}

if (require.main === module) main();
module.exports = { expand };
